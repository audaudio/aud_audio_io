// Regenerates lib/src/android/aud_io_android_bindings.dart, the JNI
// bindings of the Android classes the Dart side of aud_audio_io calls
// (ticket 21, decision 1): `node scripts/generate-android-bindings.js`.
//
// jnigen is configured by a Dart program; this script writes that program
// into .dart_tool and runs it, so that the configuration stays in a script
// of the repo. Only the members in `allowed` below are bound. jnigen needs
// a JDK - it takes the one Flutter is configured with, usually Android
// Studio's - and the Android SDK, found through ANDROID_HOME or the
// default location of Android Studio.

'use strict';

const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const output = 'lib/src/android/aud_io_android_bindings.dart';
const apiLevel = 36;

// The classes and their members to bind; nested classes are named with $.
const allowed = {
  'android.content.Context': [
    'getSystemService',
    'checkSelfPermission',
    'AUDIO_SERVICE',
  ],
  'android.media.AudioManager': [
    'getDevices',
    'getAudioDevicesForAttributes',
    'requestAudioFocus',
    'abandonAudioFocusRequest',
    'getProperty',
    'GET_DEVICES_ALL',
    'AUDIOFOCUS_GAIN',
    'AUDIOFOCUS_LOSS',
    'AUDIOFOCUS_LOSS_TRANSIENT',
    'AUDIOFOCUS_LOSS_TRANSIENT_CAN_DUCK',
    'AUDIOFOCUS_REQUEST_GRANTED',
    'AUDIOFOCUS_REQUEST_DELAYED',
    'PROPERTY_OUTPUT_SAMPLE_RATE',
    'PROPERTY_OUTPUT_FRAMES_PER_BUFFER',
  ],
  'android.media.AudioManager$OnAudioFocusChangeListener': [
    'onAudioFocusChange',
  ],
  'android.media.AudioDeviceInfo': [
    'getId',
    'getProductName',
    'getType',
    'isSink',
    'isSource',
    'getChannelCounts',
    'getSampleRates',
    /^TYPE_/,
  ],
  'android.media.AudioFocusRequest': [],
  'android.media.AudioFocusRequest$Builder': [
    '<init>',
    'setAudioAttributes',
    'setOnAudioFocusChangeListener',
    'setAcceptsDelayedFocusGain',
    'setWillPauseWhenDucked',
    'build',
  ],
  'android.media.AudioAttributes': ['USAGE_MEDIA', 'CONTENT_TYPE_MUSIC'],
  'android.media.AudioAttributes$Builder': [
    '<init>',
    'setUsage',
    'setContentType',
    'build',
  ],
  'android.os.Build': [],
  'android.os.Build$VERSION': ['SDK_INT'],
};

const preamble = `// @license
// Copyright (c) Audanika. All Rights Reserved.
//
// Use of this source code is governed by terms that can be
// found in the LICENSE file in the root of this package.

// Generated by jnigen through scripts/generate-android-bindings.js; it runs
// on Android only.
// coverage:ignore-file
// ignore_for_file: type=lint
`;

function generator(sdkRoot) {
  const classes = [
    ...new Set(Object.keys(allowed).map((name) => name.split('$')[0])),
  ];
  const members = Object.entries(allowed)
    .map(([name, list]) => {
      const entries = list.map((m) =>
        m instanceof RegExp ? `RegExp(r'${m.source}')` : `'${m}'`,
      );
      return `  r'${name}': [${entries.join(', ')}],`;
    })
    .join('\n');
  return `import 'package:jnigen/jnigen.dart';

final allowed = <String, List<Pattern>>{
${members}
};

bool matches(List<Pattern>? patterns, String name) =>
    patterns != null &&
    patterns.any((p) => p is RegExp ? p.hasMatch(name) : p == name);

Future<void> main() async {
  List<Pattern>? current;
  final generator = JniGenerator(
    input: Input(
      classes: ${JSON.stringify(classes)},
      androidSdk: AndroidSdk(
        versions: [${apiLevel}],
        sdkRoot: Uri.directory(${JSON.stringify(sdkRoot)}),
      ),
    ),
    output: Output(
      dart: DartOutput(
        path: Uri.file(${JSON.stringify(path.join(root, output))}),
        structure: OutputStructure.singleFile,
      ),
      preamble: ${JSON.stringify(preamble)},
    ),
    visitors: [
      Visitor(
        classDecl: (c) {
          current = allowed[c.binaryName];
          c.isIncluded = current != null;
        },
        method: (m) => m.isIncluded =
            matches(current, m.isConstructor ? '<init>' : m.originalName),
        field: (f) => f.isIncluded = matches(current, f.originalName),
      ),
    ],
  );
  await generator.generate();
}
`;
}

function main() {
  const env = { ...process.env };
  const sdkRoot =
    env.ANDROID_HOME ||
    env.ANDROID_SDK_ROOT ||
    path.join(os.homedir(), 'Library', 'Android', 'sdk');
  if (!fs.existsSync(path.join(sdkRoot, 'platforms', `android-${apiLevel}`))) {
    throw new Error(`No android-${apiLevel} platform in ${sdkRoot}`);
  }
  const dir = path.join(root, '.dart_tool', 'aud_jnigen');
  fs.mkdirSync(dir, { recursive: true });
  const program = path.join(dir, 'generate.dart');
  fs.writeFileSync(program, generator(sdkRoot));
  fs.mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
  const result = spawnSync('dart', ['run', program], {
    cwd: root,
    env,
    stdio: 'inherit',
  });
  process.exit(result.status ?? 1);
}

main();
